#!/usr/bin/env python3
"""Build the Information Fusion submission in a clean directory and write submission/information_fusion/.

    python3 scripts/package_infofusion.py

The journal uses single anonymized review, so the manuscript carries the author block. Output folder:
    Manuscript.pdf, Supplement.pdf, Cover_Letter.pdf, highlights.txt, figures/, source/ (LaTeX sources, as a zip too),
    declarations/ (competing interests, generative AI, CRediT texts), SUBMISSION_CHECKLIST.md
The build copies the sources into a temporary directory first, so stale auxiliary files cannot leak into the result.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MS = ROOT / "manuscript"
DEST = ROOT / "submission" / "information_fusion"

SOURCES = ["main.tex", "supplement.tex", "supplement_body.tex", "refs.bib", "elsarticle.cls",
           "elsarticle-num-names.bst", "apalike-local.bst", "Cover_Letter.tex"]


def run(cmd: list[str], cwd: Path) -> str:
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    return res.stdout + res.stderr


def build(work: Path) -> dict:
    files = list(dict.fromkeys(SOURCES + [p.name for p in sorted(MS.glob("*_data.tex"))] + [p.name for p in sorted(MS.glob("Figure_*"))]))
    for name in files:
        shutil.copy2(MS / name, work / name)
    tex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error"]
    run(tex + ["main.tex"], work)
    run(tex + ["supplement.tex"], work)
    run(["bibtex", "main"], work)
    run(["bibtex", "supplement"], work)
    for _ in range(2):
        run(tex + ["main.tex"], work)
        run(tex + ["supplement.tex"], work)
    log = run(tex + ["main.tex"], work)
    run(tex + ["Cover_Letter.tex"], work)
    run(tex + ["Cover_Letter.tex"], work)
    problems = []
    for name in ("main", "supplement"):
        text = (work / f"{name}.log").read_text(errors="ignore")
        problems += [f"{name}: {m}" for m in re.findall(r"(?m)^(?:LaTeX Warning: (?:Reference|Citation).*undefined.*|! .*)$", text)]
    pages = {n: int(re.search(r"Pages:\s+(\d+)", run(["pdfinfo", f"{n}.pdf"], work)).group(1)) for n in ("main", "supplement", "Cover_Letter")}
    bbl = (work / "main.bbl").read_text()
    return {"pages": pages, "references": len(re.findall(r"\\bibitem", bbl)), "problems": problems, "files": files}


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        info = build(work)
        if info["problems"]:
            print("build problems:", *info["problems"], sep="\n  ")
            return 1
        if DEST.exists():
            shutil.rmtree(DEST)
        (DEST / "figures").mkdir(parents=True)
        (DEST / "declarations").mkdir()
        (DEST / "source").mkdir()
        shutil.copy2(work / "main.pdf", DEST / "Manuscript.pdf")
        shutil.copy2(work / "supplement.pdf", DEST / "Supplement.pdf")
        shutil.copy2(work / "Cover_Letter.pdf", DEST / "Cover_Letter.pdf")
        shutil.copy2(MS / "highlights.txt", DEST / "highlights.txt")
        for fig in sorted(MS.glob("Figure_*.pdf")):
            shutil.copy2(fig, DEST / "figures" / fig.name)
        for name in ("Credit_Author_Statement.txt", "Declaration_of_Competing_Interest.txt", "Declaration_of_Generative_AI.txt"):
            shutil.copy2(MS / name, DEST / "declarations" / name)
        src = [n for n in info["files"] if n != "Cover_Letter.tex"] + ["main.bbl", "supplement.bbl", "supplement.aux"]
        for name in src:
            shutil.copy2(work / name, DEST / "source" / name)
        with zipfile.ZipFile(DEST / "informationfusion-latex-source.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for name in src:
                z.write(work / name, name)
    pages, refs = info["pages"], info["references"]
    checks = [
        (f"Manuscript length {pages['main']} pages (limit 35, including figures, tables, references)", pages["main"] <= 35),
        (f"{refs} references (limit 50)", refs <= 50),
    ]
    highlights = [l[2:].strip() for l in (MS / "highlights.txt").read_text().splitlines() if l.startswith("- ")]
    checks.append((f"{len(highlights)} highlights, longest {max(map(len, highlights))} characters (3 to 5 bullets, 85 characters)",
                   3 <= len(highlights) <= 5 and max(map(len, highlights)) <= 85))
    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", (MS / "main.tex").read_text(), re.S).group(1)
    words = len(re.sub(r"\\[A-Za-z]+\{?|[{}\\]", " ", abstract).split())
    checks.append((f"abstract about {words} words (limit 250; macro values counted as one word)", words <= 250))
    lines = ["# Information Fusion submission checklist (generated by scripts/package_infofusion.py)", ""]
    lines += [f"- [{'x' if ok else ' '}] {text}" for text, ok in checks]
    lines += ["", "Author actions that cannot be automated:",
              "- Complete the Elsevier declarations tool and upload the Word document it generates.",
              "- Enter the archive DOI (Option C research data) in the submission form.",
              "- Upload: Manuscript source (`source/` or the zip), Supplement.pdf as supplementary material, figures, highlights.txt, Cover_Letter.pdf.",
              "- Optional: graphical abstract (not prepared)."]
    (DEST / "SUBMISSION_CHECKLIST.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0 if all(ok for _, ok in checks) else 1


if __name__ == "__main__":
    sys.exit(main())
