"""Offline weight ablation on the stored judge outputs of the ground-truth tracks (zero API calls).

    python3 scripts/ablation_weights_offline.py

Every row saved since judgments were persisted carries the judge's confidence scores and pairwise
matrix, so the selection step can be replayed exactly under other weights. Variants:

  default      the shipped objective, w = (quality 1.0, confidence 0.2, consistency 0.3, cost 0.01)
  no-cost      w_cost = 0
  quality-only Copeland aggregate alone (confidence, consistency, cost all 0)
  SC+quality   plurality vote over extracted answers, ties broken by Copeland quality

The replay of `default` is checked against the stored OR-Select winner (fidelity) so the other
variants can be trusted. Writes manuscript/Ablation_data.tex.
"""

from __future__ import annotations

import json
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from or_select import gpqa, gsm8k, math_eval  # noqa: E402
from or_select.consistency import compute_consistency  # noqa: E402
from or_select.core import Candidate  # noqa: E402
from or_select.selection import aggregate_quality, select_best  # noqa: E402

OUT = ROOT / "outputs"
DEST = ROOT / "manuscript" / "Ablation_data.tex"

EXTRACT = {
    "gsm": lambda t: gsm8k.extract_answer(t),
    "math": lambda t: math_eval.extract_boxed(t),
    "gpqa": lambda t: gpqa.extract_choice(t),
}
CORRECT = {"gsm": gsm8k.is_correct, "math": math_eval.is_correct, "gpqa": gpqa.is_correct}
TRACKS = [
    ("GSMx", r"B$'$ GSM8K, heterog.", "gsm8k_benchmark_heterogeneous.json", "gsm", True),
    ("MATHh", "C MATH L5, homog.", "math_benchmark_full.json", "math", False),
    ("MATHx", r"C$'$ MATH L5, heterog.", "math_benchmark_heterogeneous.json", "math", True),
    ("AIMEh", "D AIME 2026, homog.", "aime_2026_benchmark.json", "math", False),
    ("AIMEx", r"D$'$ AIME 2026, heterog.", "aime_2026_heterogeneous.json", "math", True),
    ("GPQAh", "E GPQA Diamond, homog.", "gpqa_benchmark.json", "gpqa", False),
    ("GPQAx", r"E$'$ GPQA Diamond, heterog.", "gpqa_heterogeneous.json", "gpqa", True),
]
VARIANTS = ("self_consistency", "default", "no_cost", "quality_only", "sc_quality")


def mcnemar_p(b: int, c: int):
    n = b + c
    if n == 0:
        return None
    return min(1.0, 2 * sum(comb(n, i) for i in range(min(b, c) + 1)) * 0.5**n)


def fmt_p(p):
    return "--" if p is None else ("$<$0.001" if p < 0.001 else f"{p:.3f}")


def replay(row: dict, kind: str) -> dict | None:
    j = row.get("judgments")
    if not j or row.get("judge_version") != "short-answer":
        return None
    cands = []
    for i, c in enumerate(row["candidates"]):
        cid = f"c{i}"
        cand = Candidate(id=cid, text=c["text"], source_model=c["source_model"])
        cand.confidence = j["confidence"][cid]
        cand.cost = len(c["text"].split())
        cands.append(cand)
    pair = {tuple(k.split("|")): w for k, w in j["pairwise"].items()}
    quality = aggregate_quality(cands, pair)
    cons = compute_consistency(cands)
    ext = EXTRACT[kind]
    valid = {c.id: ext(c.text) is not None for c in cands}
    gt = row["ground_truth"]
    ok = lambda cid: bool(CORRECT[kind](ext(next(c for c in cands if c.id == cid).text), gt))  # noqa: E731

    out = {"self_consistency": bool(row["self_consistency"]["correct"])}
    out["cost_spread"] = 0.01 * (max(c.cost for c in cands) - min(c.cost for c in cands))
    out["quality_spread"] = max(quality.values()) - min(quality.values())
    wid, _ = select_best(cands, quality, cons, valid=valid)
    out["default"] = ok(wid)
    out["fidelity"] = str(ext(next(c for c in cands if c.id == wid).text)) == str(row["or_select"]["answer"])
    wid, _ = select_best(cands, quality, cons, w_cost=0.0, valid=valid)
    out["no_cost"] = ok(wid)
    wid, _ = select_best(cands, quality, None, w_confidence=0.0, w_consistency=0.0, w_cost=0.0, valid=valid)
    out["quality_only"] = ok(wid)
    pool = [c for c in cands if valid[c.id]] or cands
    counts: dict[str, int] = {}
    for c in pool:
        counts[str(ext(c.text))] = counts.get(str(ext(c.text)), 0) + 1
    best = max(pool, key=lambda c: (counts[str(ext(c.text))] + quality[c.id], -int(c.id[1:])))
    out["sc_quality"] = ok(best.id)
    return out


def main() -> None:
    L = ["% Generated by scripts/ablation_weights_offline.py from outputs/*.json -- do not hand-edit."]
    table = []
    pooled = {True: {v: [] for v in VARIANTS}, False: {v: [] for v in VARIANTS}}
    fid_all = [0, 0]
    for key, label, fname, kind, het in TRACKS:
        rows = [r for r in json.loads((OUT / fname).read_text())["results"] if "error" not in r]
        reps = [x for x in (replay(r, kind) for r in rows) if x is not None]
        n = len(reps)
        if n == 0:
            continue
        for v in VARIANTS:
            pooled[het][v].extend(x[v] for x in reps)
        fid = sum(x["fidelity"] for x in reps)
        fid_all[0] += fid
        fid_all[1] += n
        acc = {v: 100 * sum(x[v] for x in reps) / n for v in VARIANTS}
        table.append(
            f"{label} & {n}/{len(rows)} & {acc['self_consistency']:.1f} & {acc['default']:.1f} & "
            f"{acc['no_cost']:.1f} & {acc['quality_only']:.1f} & {acc['sc_quality']:.1f} \\\\"
        )
        print(f"{key:6} replayable {n:3}/{len(rows):3} fidelity {fid}/{n}  " + "  ".join(f"{v}={acc[v]:.1f}" for v in VARIANTS))
    L.append(r"\def\AblationTableRows{" + "\n".join(table) + "}")
    L.append(r"\def\AblationFidelityK{%d}" % fid_all[0])
    L.append(r"\def\AblationFidelityN{%d}" % fid_all[1])
    for het, tag in ((False, "Hom"), (True, "Het")):
        n = len(pooled[het]["self_consistency"])
        L.append(rf"\def\Abl{tag}N{{{n}}}")
        for v, vt in (("default", "Def"), ("no_cost", "NoCost"), ("quality_only", "QOnly"), ("sc_quality", "SCQ"), ("self_consistency", "SC")):
            k = sum(pooled[het][v])
            L.append(rf"\def\Abl{tag}{vt}Acc{{{100 * k / n:.1f}}}")
            if v != "self_consistency":
                b = sum(1 for a, s in zip(pooled[het][v], pooled[het]["self_consistency"]) if a and not s)
                c = sum(1 for a, s in zip(pooled[het][v], pooled[het]["self_consistency"]) if s and not a)
                L.append(rf"\def\Abl{tag}{vt}B{{{b}}}")
                L.append(rf"\def\Abl{tag}{vt}C{{{c}}}")
                L.append(rf"\def\Abl{tag}{vt}P{{{fmt_p(mcnemar_p(b, c))}}}")
                print(f"pooled {tag} {v:13} acc {100 * k / n:.1f} vs SC {100 * sum(pooled[het]['self_consistency']) / n:.1f}  wins {b}/{c} p={fmt_p(mcnemar_p(b, c))}")
    print("replay fidelity of the default objective:", fid_all)
    import statistics

    spreads = {"cost": [], "quality": []}
    for key, label, fname, kind, het in TRACKS:
        for r in json.loads((OUT / fname).read_text())["results"]:
            if "error" in r:
                continue
            x = replay(r, kind)
            if x is not None:
                spreads["cost"].append(x["cost_spread"])
                spreads["quality"].append(x["quality_spread"])
    cs, qs = statistics.median(spreads["cost"]), statistics.median(spreads["quality"])
    dom = sum(1 for c, q in zip(spreads["cost"], spreads["quality"]) if c > q)
    L.append(r"\def\CostSpreadMed{%.2f}" % cs)
    L.append(r"\def\QualitySpreadMed{%.2f}" % qs)
    L.append(r"\def\CostDominatesK{%d}" % dom)
    L.append(r"\def\CostDominatesN{%d}" % len(spreads["cost"]))
    print(f"median within-row spread: cost term {cs:.2f} vs quality term {qs:.2f}; cost spread > quality spread in {dom}/{len(spreads['cost'])} rows")
    DEST.write_text("\n".join(L) + "\n")
    print("wrote", DEST)


if __name__ == "__main__":
    main()
