"""Extract track/ablation/judge-validation numbers from outputs/*.json into
LaTeX \\def macros consumed by the manuscript's tables and figures.

Run from manuscript/ (writes alongside the figure .tex files it feeds):

    PYTHONPATH=.. python3 ../scripts/create_manuscript_tables.py

Mirrors the inventor_project pattern (create_publication_figures.py writing
Figure_N_..._data.tex): numbers are computed here, once, from the same
outputs/*.json the prose in main.tex was written from, so the manuscript
never hand-types a number that isn't traceable to a run artifact.
"""
import argparse
import json
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(REPO_ROOT, "outputs")
DEST = os.path.join(REPO_ROOT, "manuscript", "Figure_2_Accuracy_data.tex")
WORKED_EXAMPLE_SRC = os.path.join(
    OUT_DIR, "runs", "summarize-the-plot-of-hamlet-in-one-sentence", "selection.json"
)
WORKED_EXAMPLE_DEST = os.path.join(REPO_ROOT, "manuscript", "Figure_3_WorkedExample_data.tex")

# Must match the default weights stated in main.tex, Section 3.2 (Formal Model).
W1_QUALITY, W2_CONFIDENCE, W3_COST, W4_CONSISTENCY = 1.0, 0.2, 0.01, 0.3


def worked_example():
    """Recover quality_i for the real Track-A Hamlet run by inverting the
    known scoring formula (same inversion scripts/ablation_consistency.py
    performs), then emit \\def macros for Table 4 and Figure 3. Asserts the
    recovered ranking's argmax matches the run's saved winner_id, so a
    violated inversion assumption fails loudly instead of silently
    producing a wrong worked example."""
    with open(WORKED_EXAMPLE_SRC) as f:
        run = json.load(f)
    candidates = {c["id"]: c for c in run["candidates"]}
    ids = [c["id"] for c in run["candidates"]]
    n = len(ids)
    texts = {i: candidates[i]["text"].strip() for i in ids}
    consistency = {i: sum(1 for j in ids if texts[j] == texts[i]) / n for i in ids}

    rows = []
    for i in ids:
        score = run["scores"][i]
        confidence = candidates[i]["confidence"]
        cost = candidates[i]["cost"]
        cons = consistency[i]
        quality = (score - W2_CONFIDENCE * confidence - W4_CONSISTENCY * cons + W3_COST * cost) / W1_QUALITY
        rows.append(
            {
                "id": i,
                "confidence": confidence,
                "cost": cost,
                "consistency": cons,
                "quality": quality,
                "score": score,
            }
        )

    computed_winner = max(rows, key=lambda r: r["score"])["id"]
    assert computed_winner == run["winner_id"], (
        f"worked example inversion inconsistent: argmax={computed_winner}, "
        f"saved winner={run['winner_id']}"
    )

    lines = [
        "% Generated by scripts/create_manuscript_tables.py from "
        "outputs/runs/summarize-the-plot-of-hamlet-in-one-sentence/selection.json"
        " -- do not hand-edit."
    ]
    table_rows = []
    bar_coords = {"quality": [], "confidence": [], "consistency": [], "cost": []}
    for r in rows:
        marker = r"$^\ast$" if r["id"] == run["winner_id"] else ""
        table_rows.append(
            f"{r['id']}{marker} & {r['quality']:.3f} & {r['confidence']:.2f} & "
            f"{r['consistency']:.2f} & {r['cost']:d} & {r['score']:.3f} \\\\"
        )
        bar_coords["quality"].append(f"({r['id']},{W1_QUALITY * r['quality']:.4f})")
        bar_coords["confidence"].append(f"({r['id']},{W2_CONFIDENCE * r['confidence']:.4f})")
        bar_coords["consistency"].append(f"({r['id']},{W4_CONSISTENCY * r['consistency']:.4f})")
        bar_coords["cost"].append(f"({r['id']},{-W3_COST * r['cost']:.4f})")

    lines.append(r"\def\WorkedExampleTableRows{" + "\n".join(table_rows) + "}")
    lines.append(r"\def\WorkedExampleWinner{" + run["winner_id"] + "}")
    lines.append(r"\def\WorkedExampleQualityBars{" + " ".join(bar_coords["quality"]) + "}")
    lines.append(r"\def\WorkedExampleConfidenceBars{" + " ".join(bar_coords["confidence"]) + "}")
    lines.append(r"\def\WorkedExampleConsistencyBars{" + " ".join(bar_coords["consistency"]) + "}")
    lines.append(r"\def\WorkedExampleCostBars{" + " ".join(bar_coords["cost"]) + "}")

    with open(WORKED_EXAMPLE_DEST, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", WORKED_EXAMPLE_DEST)
    for r in rows:
        print(r)


def load(name, source_dir=OUT_DIR):
    """RewardBench is always read from OUT_DIR (never archived mid-run);
    the five ground-truth tracks accept --source-dir so this script can
    regenerate from an archived snapshot (e.g. outputs/pilot_pre_extraction_fix)
    without touching a live run's in-progress output files."""
    with open(os.path.join(source_dir, name)) as f:
        return json.load(f)


def pct(num, den):
    return 100.0 * num / den if den else 0.0


def track_row(label, data, methods=("or_select", "self_consistency", "greedy", "kemeny_young")):
    acc = data["accuracy_of_valid"]
    n_valid = data["n_valid"]
    n_total = data["n_total"]
    row = {"label": label, "n_valid": n_valid, "n_total": n_total}
    for m in methods:
        if m in acc:
            a = acc[m]
            correct = round(a * n_valid) if isinstance(a, float) and a <= 1.0 else a
            row[m] = a * 100.0 if a <= 1.0 else pct(a, n_valid)
    disagreement = data.get("disagreement", {})
    row["n_disagreements"] = disagreement.get("n_disagreements", 0)
    row["or_corrects_sc"] = disagreement.get("n_or_select_corrects_self_consistency", 0)
    row["sc_corrects_or"] = disagreement.get("n_self_consistency_corrects_or_select", 0)
    return row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        default=OUT_DIR,
        help="Directory to read the five ground-truth track JSON files from "
        "(default: outputs/). RewardBench is always read from outputs/. "
        "Pass outputs/pilot_pre_extraction_fix to regenerate from an "
        "archived snapshot instead of a live run's in-progress files.",
    )
    args = parser.parse_args()

    gsm8k = load("gsm8k_benchmark_initial.json")  # never archived; always the live file
    math5 = load("math_benchmark_full.json", args.source_dir)
    aime_h = load("aime_2026_benchmark.json", args.source_dir)
    aime_x = load("aime_2026_heterogeneous.json", args.source_dir)
    gpqa_h = load("gpqa_benchmark.json", args.source_dir)
    gpqa_x = load("gpqa_heterogeneous.json", args.source_dir)
    rb = load("reward_bench_benchmark.json")

    rows = [
        track_row("GSM8K-B", gsm8k, methods=("or_select", "self_consistency", "greedy")),
        track_row("MATH5-C", math5),
        track_row("AIME-D", aime_h),
        track_row("AIME-Dx", aime_x),
        track_row("GPQA-E", gpqa_h),
        track_row("GPQA-Ex", gpqa_x),
    ]

    lines = ["% Generated by scripts/create_manuscript_tables.py from outputs/*.json -- do not hand-edit."]
    coords_or, coords_sc, coords_greedy, coords_ky = [], [], [], []
    for r in rows:
        lab = r["label"]
        coords_or.append(f"({lab},{r.get('or_select', 0):.1f})")
        coords_sc.append(f"({lab},{r.get('self_consistency', 0):.1f})")
        coords_greedy.append(f"({lab},{r.get('greedy', 0):.1f})")
        if "kemeny_young" in r:
            coords_ky.append(f"({lab},{r.get('kemeny_young', 0):.1f})")

    lines.append(r"\def\TrackLabels{" + ",".join(r["label"] for r in rows) + "}")
    lines.append(r"\def\ORSelectCoordinates{" + " ".join(coords_or) + "}")
    lines.append(r"\def\SelfConsistencyCoordinates{" + " ".join(coords_sc) + "}")
    lines.append(r"\def\GreedyCoordinates{" + " ".join(coords_greedy) + "}")
    lines.append(r"\def\KemenyYoungCoordinates{" + " ".join(coords_ky) + "}")

    rb_cats = rb["category_scores"]
    lines.append(r"\def\RBChatAcc{%.1f}" % (rb_cats["Chat"]["accuracy"] * 100))
    lines.append(r"\def\RBChatRows{%d}" % rb_cats["Chat"]["n_rows"])
    lines.append(r"\def\RBReasoningAcc{%.1f}" % (rb_cats["Reasoning"]["accuracy"] * 100))
    lines.append(r"\def\RBReasoningRows{%d}" % rb_cats["Reasoning"]["n_rows"])
    lines.append(r"\def\RBChatHardAcc{%.1f}" % (rb_cats["Chat Hard"]["accuracy"] * 100))
    lines.append(r"\def\RBChatHardRows{%d}" % rb_cats["Chat Hard"]["n_rows"])
    lines.append(r"\def\RBSafetyAcc{%.1f}" % (rb_cats["Safety"]["accuracy"] * 100))
    lines.append(r"\def\RBSafetyRows{%d}" % rb_cats["Safety"]["n_rows"])
    lines.append(r"\def\RBOverallAcc{%.1f}" % (rb["overall_accuracy"] * 100))
    lines.append(r"\def\RBN{%d}" % rb["n_valid"])
    rb_ci_lo, rb_ci_hi = rb["overall_ci95_micro"]
    lines.append(r"\def\RBOverallCILow{%.1f}" % (rb_ci_lo * 100))
    lines.append(r"\def\RBOverallCIHigh{%.1f}" % (rb_ci_hi * 100))

    with open(DEST, "w") as f:
        f.write("\n".join(lines) + "\n")

    print("wrote", DEST)
    for r in rows:
        print(r)

    worked_example()


if __name__ == "__main__":
    main()
