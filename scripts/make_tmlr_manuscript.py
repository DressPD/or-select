#!/usr/bin/env python3
"""Generate the anonymized TMLR submission source from the main manuscript sources.

The main manuscript (manuscript/main.tex) and its online supplement
(manuscript/supplement_body.tex) remain the single source of truth. This script
writes manuscript/main_tmlr.tex, which

* uses the TMLR style in double-blind submission mode,
* removes author, affiliation, journal, keyword and declaration blocks,
* replaces the identifying data-availability paragraph with an anonymous one,
* folds the online supplement in as an appendix (one PDF, as TMLR expects).

Usage:  python3 scripts/make_tmlr_manuscript.py
"""
from pathlib import Path
import re

MS = Path(__file__).resolve().parent.parent / "manuscript"
main = (MS / "main.tex").read_text(encoding="utf-8")
supp = (MS / "supplement_body.tex").read_text(encoding="utf-8")

data_inputs = re.findall(r"^\\input\{[A-Za-z_0-9]+_data\.tex\}\s*$", main, re.M)

abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", main, re.S).group(1).strip()
title = re.search(r"\\title\{(.*?)\}\s*\n", main).group(1)

body = main[main.index("\\section{Introduction}"):main.index("\\section*{Data and code availability}")]
# Cross-references into the former separate supplement now point into the appendix.
body = re.sub(r"\\ref\{S-", r"\\ref{", body)
body = body.replace("Online Supplement", "Appendix").replace("the supplement", "the appendix")
body = body.replace("The supplement", "The appendix").replace("supplement.", "appendix.")

appendix = supp
# Cross-references from the former supplement into the main text lose their M- prefix.
appendix = re.sub(r"\\ref\{M-", r"\\ref{", appendix)
appendix = re.sub(r"\\eqref\{M-", r"\\eqref{", appendix)
# The main text and the supplement each defined sec:baselines; keep the main one.
appendix = appendix.replace("\\label{sec:baselines}", "\\label{sec:s-baselines}")
appendix = appendix.replace("\\ref{sec:baselines}", "\\ref{sec:s-baselines}")

anon_data = r"""\section*{Data and code availability}
Code, tables, pre-registration documents and run files are provided in an
anonymized archive with this submission; a public, permanently archived release
will be cited in the camera-ready version. The run archive excludes GPQA
records containing password-gated question text; access to that benchmark
follows its distribution conditions. The analysis scripts regenerate all tables
from stored runs and include the GPQA generation workflow.
"""

preamble = r"""% GENERATED by scripts/make_tmlr_manuscript.py -- do not edit by hand.
\documentclass[10pt]{article}
\usepackage{tmlr}
\usepackage{hyperref}
\usepackage{url}
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage{amsthm}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage{seqsplit}
\usepackage[section]{placeins}

\newtheorem{proposition}{Proposition}[section]
\newtheorem{theorem}{Theorem}[section]
\newtheorem{lemma}{Lemma}[section]
\newtheorem{corollary}{Corollary}[section]

""" + "\n".join(data_inputs) + r"""

\title{""" + title + r"""}
\author{\name Anonymous authors \\ \addr Paper under double-blind review}

\begin{document}
\maketitle

\begin{abstract}
""" + abstract + r"""
\end{abstract}

"""

closing = r"""
\bibliographystyle{tmlr}
\bibliography{refs}

\appendix
\renewcommand{\thetable}{\Alph{section}.\arabic{table}}
\renewcommand{\thefigure}{\Alph{section}.\arabic{figure}}
""" + appendix + "\n\\end{document}\n"

out = preamble + body + anon_data + closing
(MS / "main_tmlr.tex").write_text(out, encoding="utf-8")
print(f"wrote {MS / 'main_tmlr.tex'} ({len(out.splitlines())} lines)")
