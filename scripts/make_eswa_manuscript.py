#!/usr/bin/env python3
"""Generate the double-anonymized Expert Systems with Applications sources from the main manuscript.

The journal follows double anonymized review: the title page (author details, acknowledgments, competing interests)
and the anonymized manuscript are separate files, and supplementary material must also carry no identifying
information. manuscript/main.tex and manuscript/supplement.tex stay the single source of truth. This script writes
    manuscript/main_eswa.tex        anonymous article (elsarticle, no author block, no CRediT or competing-interest sections)
    manuscript/supplement_eswa.tex  anonymous supplement
Author details live in manuscript/Submission_Title_Page.tex.

Usage:  python3 scripts/make_eswa_manuscript.py
"""
from pathlib import Path
import re

MS = Path(__file__).resolve().parent.parent / "manuscript"
main = (MS / "main.tex").read_text(encoding="utf-8")
supp = (MS / "supplement.tex").read_text(encoding="utf-8")

preamble = main[: main.index("\\begin{document}")]
preamble = preamble.replace("\\externaldocument[S-]{supplement}", "\\externaldocument[S-]{supplement_eswa}")
preamble = "% GENERATED by scripts/make_eswa_manuscript.py -- do not edit by hand.\n" + preamble

title = re.search(r"\\title\{(.*?)\}\s*\n", main).group(1)
abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", main, re.S).group(1).strip()
keywords = re.search(r"\\begin\{keyword\}(.*?)\\end\{keyword\}", main, re.S).group(1).strip()

frontmatter = (
    "\\begin{document}\n\n\\begin{frontmatter}\n\n"
    f"\\title{{{title}}}\n\n"
    f"\\begin{{abstract}}\n{abstract}\n\\end{{abstract}}\n\n"
    f"\\begin{{keyword}}\n{keywords}\n\\end{{keyword}}\n\n\\end{{frontmatter}}\n\n"
)

body = main[main.index("\\section{Introduction}"):main.index("\\section*{Data and code availability}")]

anon_data = r"""\section*{Data availability statement}
The code, tables, pre-registration documents and stored run files that support the findings are archived in a
public repository. To preserve anonymity during double anonymized review, the persistent identifier is given in the
submission form and an anonymized copy is provided with the submission; the identifier will be cited in the
accepted version. The archive excludes GPQA records containing password-gated question text, which cannot be
redistributed; access to that benchmark follows its distribution conditions. The analysis scripts regenerate all
tables from the stored runs and include the GPQA generation workflow.

"""

# Funding and generative-AI declarations stay in the manuscript (the AI statement must precede the references);
# CRediT and the competing-interest declaration move to the title page.
tail = main[main.index("\\section*{Funding}"):main.index("\\bibliographystyle")]
closing = "\n\\bibliographystyle{apalike-local}\n\\bibliography{refs}\n\n\\end{document}\n"
(MS / "main_eswa.tex").write_text(preamble + frontmatter + body + anon_data + tail + closing, encoding="utf-8")

s = supp.replace("\\externaldocument[M-]{main}", "\\externaldocument[M-]{main_eswa}")
s = s.replace("\\author{Aris Dressino}", "\\author{}")
(MS / "supplement_eswa.tex").write_text("% GENERATED by scripts/make_eswa_manuscript.py -- do not edit by hand.\n" + s, encoding="utf-8")
print("wrote main_eswa.tex and supplement_eswa.tex")
