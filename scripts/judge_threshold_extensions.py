"""Extensions of the judge-accuracy threshold: N = 7, wrong-answer structure, a large-N lower bound, and the cost term.

    python3 scripts/judge_threshold_extensions.py        # writes manuscript/ThresholdExt_data.tex

Zero API calls. Builds on scripts/judge_threshold_general.py.

  1. Exact q*(p, N) for N = 7 (2^21 comparison outcomes per k) next to N = 3..6.
  2. Sensitivity to the *structure* of wrong answers: instead of one attractor, wrong answers are drawn uniformly from D
     values (D = 1: all wrong answers coincide; D = 3: the distractors of a four-option question; D -> infinity: all distinct).
  3. A rigorous large-N lower bound on the threshold. With distinct wrong answers plurality's error is exactly
         err_V(N) = (1-p)^N + (N-1) p (1-p)^(N-1)        (decay rate  -ln(1-p)).
     Copeland errs at least on the event {k = ceil(eta N) correct, some wrong candidate beats all of them}, whose probability
     decays at rate  Lambda(p, q) = min_{eta >= 1 - 1/(2q)} KL(eta || p) + eta ln(1/(1-q)).  If Lambda < -ln(1-p), then for all
     large N Copeland is strictly less accurate than plurality, so  liminf_N q*(p, N) >= q_Lambda(p),  the root of Lambda = -ln(1-p).
  4. The cost term: a length score independent of correctness, weight lambda against the Copeland score (scaled to [0, 1]).
"""

from __future__ import annotations

import itertools
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import judge_threshold_general as gen  # noqa: E402

DEST = ROOT / "manuscript" / "ThresholdExt_data.tex"


def vote_acc_given_k_uniform(N: int, k: int, D: int) -> float:
    """P(plurality correct | k correct) when each wrong answer is uniform over D wrong values; ties uniform over answers."""
    if k == N:
        return 1.0
    total = 0.0
    r = N - k
    for comp in itertools.product(range(r + 1), repeat=D - 1):
        s = sum(comp)
        if s > r:
            continue
        counts_w = list(comp) + [r - s]
        pm = math.factorial(r) / math.prod(math.factorial(c) for c in counts_w) * (1.0 / D) ** r
        counts = ([k] if k else []) + [c for c in counts_w if c]
        top = max(counts)
        tied = [c == top for c in counts]
        total += pm * (tied[0] / sum(tied) if k else 0.0)
    return total


def gap_uniform_D(N: int, p: float, D: int, q: float) -> float:
    Q = gen.uniform_Q(N, q)
    return sum(
        math.comb(N, k) * p**k * (1 - p) ** (N - k) * (gen.copeland_acc_given_k(N, k, Q) - vote_acc_given_k_uniform(N, k, D))
        for k in range(N + 1)
    )


def q_star_uniform_D(N: int, p: float, D: int, tol: float = 1e-4) -> float:
    lo, hi = 0.5, 1.0
    while hi - lo > tol:
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if gap_uniform_D(N, p, D, mid) < 0 else (lo, mid)
    return hi


def kl(a: float, b: float) -> float:
    return sum(x * math.log(x / y) for x, y in ((a, b), (1 - a, 1 - b)) if x > 0)


def Lambda(p: float, q: float) -> float:
    lo = max(0.0, 1 - 1 / (2 * q))
    etas = np.linspace(lo, 1.0 - 1e-9, 4001)
    return float(min(kl(e, p) + e * math.log(1 / (1 - q)) for e in etas))


def q_lambda(p: float) -> float:
    """Root of Lambda(p, q) = -ln(1-p); Lambda is increasing in q."""
    target = -math.log(1 - p)
    lo, hi = 0.5001, 0.99999
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if Lambda(p, mid) < target else (lo, mid)
    return hi


def vote_err_closed(N: int, p: float) -> float:
    return (1 - p) ** N + (N - 1) * p * (1 - p) ** (N - 1)


def cost_accuracy(N: int, p: float, q: float, lam: float, n: int = 100000, seed: int = 5) -> float:
    """Accuracy when selection maximizes (Copeland score)/(N-1) - lam * L_i with L_i ~ U(0,1) independent of correctness."""
    rng = np.random.default_rng(seed)
    iu = np.triu_indices(N, 1)
    ok = rng.random((n, N)) < p
    a, b = ok[:, iu[0]], ok[:, iu[1]]
    first = rng.random((n, len(iu[0]))) < np.where(a & ~b, q, np.where(b & ~a, 1 - q, 0.5))
    score = np.zeros((n, N))
    for col in range(len(iu[0])):
        score[np.arange(n), iu[0][col]] += first[:, col]
        score[np.arange(n), iu[1][col]] += ~first[:, col]
    length = rng.random((n, N))
    pick = np.argmax(score / (N - 1) - lam * length + 1e-9 * rng.random((n, N)), axis=1)
    return float(ok[np.arange(n), pick].mean())


def main() -> None:
    L = ["% Generated by scripts/judge_threshold_extensions.py -- do not hand-edit."]

    # 1. N = 7 exact
    n7 = [f"{gen.q_star_exact(7, p, rho, tol=1e-4):.3f}" for rho in (0.0, 0.5) for p in (0.5, 0.8)]
    L.append(r"\def\ThresholdNSevenRow{7 & " + " & ".join(n7) + r" \\}")
    print("N=7", n7)

    # 2. wrong-answer structure (N = 4, p = 0.8 and 0.5)
    rows = []
    for D in (1, 2, 3, 8):
        cells = [f"{q_star_uniform_D(N, p, D):.3f}" for N in (4, 5) for p in (0.5, 0.8)]
        rows.append(f"{D} & " + " & ".join(cells) + r" \\")
        print("D", D, cells)
    rows.append("$\\infty$ & " + " & ".join(f"{gen.q_star_exact(N, p, 0.0):.3f}" for N in (4, 5) for p in (0.5, 0.8)) + r" \\")
    L.append(r"\def\ThresholdDRows{" + "\n".join(rows) + "}")

    # 3. large-N lower bound
    rows = []
    for p in (0.5, 0.6, 0.7, 0.8, 0.9):
        ql = q_lambda(p)
        ex6 = gen.q_star_exact(6, p, 0.0)
        rows.append(f"{p:.1f} & {-math.log(1 - p):.3f} & {ql:.3f} & {ex6:.3f} \\\\")
        print(f"p={p}: vote rate {-math.log(1 - p):.3f}, q_Lambda={ql:.3f}, exact q*(N=6)={ex6:.3f}")
        # sanity: below q_Lambda, vote error (closed form) is smaller than Copeland's lower-bounded rate for large N
        assert Lambda(p, ql - 0.01) < -math.log(1 - p) < Lambda(p, min(ql + 0.01, 0.99999))
    L.append(r"\def\ThresholdLambdaRows{" + "\n".join(rows) + "}")
    for N in (3, 6, 20):  # closed form for plurality error (distinct wrong answers) against vote_acc_given_k
        exact = 1 - sum(math.comb(N, k) * 0.7**k * 0.3 ** (N - k) * gen.vote_acc_given_k(N, k, 0.0) for k in range(N + 1))
        assert abs(exact - vote_err_closed(N, 0.7)) < 1e-12, N

    # 4. cost term
    rows = []
    for lam in (0.0, 0.25, 1.0, 4.0, 1e6):
        acc = [100 * cost_accuracy(3, 0.8, q, lam) for q in (0.6, 0.9)]
        name = "$\\infty$ (shortest)" if lam >= 1e5 else f"{lam:g}"
        rows.append(f"{name} & " + " & ".join(f"{a:.1f}" for a in acc) + r" \\")
        print("lambda", lam, [round(a, 1) for a in acc])
    L.append(r"\def\ThresholdCostRows{" + "\n".join(rows) + "}")
    DEST.write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
