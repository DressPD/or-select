"""Headroom of the stored pools: how much any selector could gain over plurality voting.

    python3 scripts/headroom.py

Zero API calls. For every stored problem with candidates: plurality (stored self-consistency), the oracle that returns a correct
candidate whenever the pool contains one, and the number of problems where the oracle beats plurality. This bounds the gain of
every selector on these pools. Writes manuscript/Headroom_data.tex.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
import judge_threshold_theory as th  # noqa: E402
from usc_baseline import rows  # noqa: E402

DEST = ROOT / "manuscript" / "Headroom_data.tex"


def main() -> None:
    groups: dict = {}
    for key, label, kind, het, row in rows():
        ok = [bool(th.CORRECT[kind](th.EXTRACT[kind](c["text"]), row["ground_truth"])) for c in row["candidates"]]
        sc = bool(row["self_consistency"]["correct"])
        r = groups.setdefault(het, {"n": 0, "sc": 0, "oracle": 0, "room": 0, "none": 0})
        r["n"] += 1
        r["sc"] += sc
        r["oracle"] += any(ok)
        r["room"] += any(ok) and not sc
        r["none"] += not any(ok)
    lines = ["% Generated by scripts/headroom.py -- do not hand-edit."]
    for het, r in sorted(groups.items()):
        n, tag = r["n"], "Het" if het else "Hom"
        print(f"{tag} n={n}: plurality {100 * r['sc'] / n:.1f}%, oracle {100 * r['oracle'] / n:.1f}%, "
              f"headroom {100 * r['room'] / n:.1f} points = {r['room']} problems, pools without a correct answer {r['none']}")
        lines += [rf"\def\Head{tag}N{{{n}}}", rf"\def\Head{tag}Plur{{{100 * r['sc'] / n:.1f}}}", rf"\def\Head{tag}Oracle{{{100 * r['oracle'] / n:.1f}}}",
                  rf"\def\Head{tag}Room{{{100 * r['room'] / n:.1f}}}", rf"\def\Head{tag}RoomN{{{r['room']}}}", rf"\def\Head{tag}None{{{r['none']}}}"]
    DEST.write_text("\n".join(lines) + "\n")
    print("wrote", DEST)


if __name__ == "__main__":
    main()
