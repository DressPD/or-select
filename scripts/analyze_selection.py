"""Candidate-level audit of the ground-truth tracks: headroom, selection recovery, and per-generator
selection share. Reads outputs/*.json only (no API calls); writes manuscript/Selection_data.tex.

    python3 scripts/analyze_selection.py

Why: accuracy of a selector is only interpretable against what was available to select from. For
every graded row we know all N candidate texts, so we can score each candidate and report
  * mean candidate accuracy  (what a random pick gets: the floor),
  * oracle accuracy          (any candidate correct: the ceiling),
  * recovery                 (selector - floor) / (oracle - floor), the metric Landesberg (2026) advocates,
and, for the heterogeneous pools, how often OR-Select picks each generator's candidate versus how
accurate that generator's candidates are.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from or_select import gpqa, gsm8k, math_eval, mmlu_pro  # noqa: E402
from or_select.pipeline import canonical_model  # noqa: E402

OUT = ROOT / "outputs"
DEST = ROOT / "manuscript" / "Selection_data.tex"

# key, label, file, grader(text, ground_truth) -> bool
GRADERS = {
    "gsm": lambda t, gt: gsm8k.is_correct(gsm8k.extract_answer(t), gt),
    "math": lambda t, gt: math_eval.is_correct(math_eval.extract_boxed(t), gt),
    "gpqa": lambda t, gt: gpqa.is_correct(gpqa.extract_choice(t), gt),
    "mmlu": lambda t, gt: mmlu_pro.is_correct(mmlu_pro.extract_choice(t), gt),
}
TRACKS = [
    ("GSMh", "B --- GSM8K, homog.", "gsm8k_benchmark_initial.json", "gsm"),
    ("GSMx", r"B$'$ --- GSM8K, heterog.", "gsm8k_benchmark_heterogeneous.json", "gsm"),
    ("MATHh", "C --- MATH L5, homog.", "math_benchmark_full.json", "math"),
    ("MATHx", r"C$'$ --- MATH L5, heterog.", "math_benchmark_heterogeneous.json", "math"),
    ("AIMEh", "D --- AIME 2026, homog.", "aime_2026_benchmark.json", "math"),
    ("AIMEx", r"D$'$ --- AIME 2026, heterog.", "aime_2026_heterogeneous.json", "math"),
    ("GPQAh", "E --- GPQA Diamond, homog.", "gpqa_benchmark.json", "gpqa"),
    ("GPQAx", r"E$'$ --- GPQA Diamond, heterog.", "gpqa_heterogeneous.json", "gpqa"),
    ("AIME25h", r"F --- AIME 2025, homog.", "aime_2025_benchmark.json", "math"),
    ("MMLUh", r"G --- MMLU-Pro, homog.", "mmlu_pro_benchmark.json", "mmlu"),
]
SHORT = {
    "nvidia/nemotron-3.5-lightning:free": "Nemotron-3.5 (judge model)",
    "poolside/laguna-s-2.1:free": "Laguna-S 2.1",
    "xingchen-agi/xing4.0-29b-a4b:free": "Xing4.0-29B",
    "cohere/north-mini-code:free": "North-Mini-Code",
    "liquid/lfm-2.5-2.6b:free": "LFM-2.5 2.6B",
}


def pct(k, n):
    return f"{100 * k / n:.1f}" if n else "--"


def winner_source(row: dict) -> str | None:
    text = (row.get("winner_texts") or {}).get("or_select")
    if text is None:
        return None
    srcs = {canonical_model(c["source_model"]) for c in row["candidates"] if c["text"] == text}
    return next(iter(srcs)) if len(srcs) == 1 else None


def main() -> None:
    L = ["% Generated by scripts/analyze_selection.py from outputs/*.json -- do not hand-edit."]
    recovery_rows = []
    pooled = defaultdict(lambda: [0, 0, 0, 0])  # model -> [cand n, cand correct, picks, picks correct]
    pooled_rows = 0
    for key, label, fname, g in TRACKS:
        grade = GRADERS[g]
        if not (OUT / fname).exists():
            continue
        rows = [
            r
            for r in json.loads((OUT / fname).read_text())["results"]
            if "error" not in r and r.get("judge_version") == "short-answer"
        ]
        n_cand = k_cand = oracle = or_k = sc_k = 0
        floor_sum = 0.0
        for r in rows:
            flags = [bool(grade(c["text"], r["ground_truth"])) for c in r["candidates"]]
            n_cand += len(flags)
            k_cand += sum(flags)
            floor_sum += sum(flags) / len(flags)
            oracle += any(flags)
            or_k += bool(r["or_select"]["correct"])
            sc_k += bool(r["self_consistency"]["correct"])
            if key.endswith("x"):
                src = winner_source(r)
                for c, ok in zip(r["candidates"], flags):
                    m = canonical_model(c["source_model"])
                    pooled[m][0] += 1
                    pooled[m][1] += ok
                if src:
                    pooled[src][2] += 1
                    pooled[src][3] += bool(r["or_select"]["correct"])
                pooled_rows += 1
        n = len(rows)
        floor = floor_sum / n * 100
        orp, scp, orc = 100 * or_k / n, 100 * sc_k / n, 100 * oracle / n

        def rec(sel):
            return f"{100 * (sel - floor) / (orc - floor):.0f}" if orc - floor > 1e-9 else "--"

        recovery_rows.append(
            f"{label} & {n} & {floor:.1f} & {scp:.1f} & {orp:.1f} & {orc:.1f} & {rec(scp)} & {rec(orp)} \\\\"
        )
        L.append(rf"\def\Floor{key}{{{floor:.1f}}}")
        L.append(rf"\def\Oracle{key}{{{orc:.1f}}}")
        print(f"{key:6} n={n:3} floor={floor:5.1f} SC={scp:5.1f} OR={orp:5.1f} oracle={orc:5.1f} recov SC={rec(scp)} OR={rec(orp)}")
    L.append(r"\def\RecoveryTableRows{" + "\n".join(recovery_rows) + "}")

    sel_rows = []
    total_picks = sum(v[2] for v in pooled.values())
    for m, (nc, kc, np_, kp) in sorted(pooled.items(), key=lambda kv: -kv[1][0]):
        sel_rows.append(
            f"{SHORT.get(m, m)} & {nc} & {pct(kc, nc)} & {np_} ({pct(np_, total_picks)}\\%) & {pct(kp, np_)} \\\\"
        )
        print(f"  {m:40} cands={nc:5} acc={pct(kc, nc):>5} picks={np_:4} ({pct(np_, total_picks)}%) pick-acc={pct(kp, np_)}")
    L.append(r"\def\SelectionTableRows{" + "\n".join(sel_rows) + "}")
    L.append(r"\def\SelectionRows{%d}" % pooled_rows)
    names = {
        "nvidia/nemotron-3.5-lightning:free": "Nemotron",
        "cohere/north-mini-code:free": "Cohere",
        "poolside/laguna-s-2.1:free": "Laguna",
        "xingchen-agi/xing4.0-29b-a4b:free": "Xingchen",
    }
    for m, tag in names.items():
        nc, kc, np_, kp = pooled.get(m, [0, 0, 0, 0])
        L.append(rf"\def\PickShare{tag}{{{pct(np_, total_picks)}}}")
        L.append(rf"\def\CandAcc{tag}{{{pct(kc, nc)}}}")
        L.append(rf"\def\PickAcc{tag}{{{pct(kp, np_)}}}")
        L.append(rf"\def\CandN{tag}{{{nc}}}")
    top = max(pooled.items(), key=lambda kv: kv[1][2])
    L.append(r"\def\SelectionTopSharePct{%s}" % pct(top[1][2], total_picks))
    L.append(r"\def\SelectionXingchenCands{%d}" % pooled.get("xingchen-agi/xing4.0-29b-a4b:free", [0])[0])

    # Does OR-Select simply prefer the longest candidate? (chance level = mean 1/N)
    for tag, het in (("Hom", False), ("Het", True)):
        hit = tot = 0
        chance = 0.0
        words_won = words_all = 0.0
        for key, _label, fname, _g in TRACKS:
            if key.endswith("x") != het or not (OUT / fname).exists():
                continue
            for r in json.loads((OUT / fname).read_text())["results"]:
                if "error" in r or not r.get("winner_texts") or r.get("judge_version") != "short-answer":
                    continue
                lens = [len(c["text"]) for c in r["candidates"]]
                w = len(r["winner_texts"]["or_select"])
                tot += 1
                hit += w == max(lens)
                chance += 1 / len(lens)
                words_won += w
                words_all += sum(lens) / len(lens)
        L.append(rf"\def\LongestPick{tag}K{{{hit}}}")
        L.append(rf"\def\LongestPick{tag}N{{{tot}}}")
        L.append(rf"\def\LongestPick{tag}Chance{{{100 * chance / tot:.0f}}}")
        L.append(rf"\def\LongestPick{tag}Pct{{{100 * hit / tot:.0f}}}")
        L.append(rf"\def\WinnerLenRatio{tag}{{{words_won / words_all:.2f}}}")
        print(f"longest-candidate pick [{tag}]: {hit}/{tot} = {100 * hit / tot:.0f}% (chance {100 * chance / tot:.0f}%), winner/mean length = {words_won / words_all:.2f}")
    DEST.write_text("\n".join(L) + "\n")
    print("wrote", DEST, "| heterogeneous rows pooled:", pooled_rows)


if __name__ == "__main__":
    main()
