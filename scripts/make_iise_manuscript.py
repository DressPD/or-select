#!/usr/bin/env python3
"""Generate the anonymous (double-blind) IISE Transactions sources from the main manuscript.

manuscript/main.tex and manuscript/supplement.tex stay the single source of truth. This script writes
    manuscript/main_iise.tex        blind article: 11 pt, 1 inch margins, 1.5 spacing, natbib author-year
    manuscript/supplement_iise.tex  blind online supplement (appendices are supplied as supplemental material)
following the IISE Transactions template text (see docs/venue_decision.md for what was and was not verified).

Usage:  python3 scripts/make_iise_manuscript.py
"""
from pathlib import Path
import re

MS = Path(__file__).resolve().parent.parent / "manuscript"
main = (MS / "main.tex").read_text(encoding="utf-8")
supp = (MS / "supplement.tex").read_text(encoding="utf-8")

data_inputs = re.findall(r"^\\input\{[A-Za-z_0-9]+_data\.tex\}\s*$", main, re.M)
title = re.search(r"\\title\{(.*?)\}\s*\n", main).group(1)
abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", main, re.S).group(1).strip()
keywords = re.search(r"\\begin\{keyword\}(.*?)\\end\{keyword\}", main, re.S).group(1).strip().replace("\\sep", ";")

body = main[main.index("\\section{Introduction}"):main.index("\\section*{Data and code availability}")]
body = body.replace("Online Supplement", "Online Supplement")  # name kept: supplied as supplemental online material
# Venue-specific related work: IISE Transactions neighbours (verified via Crossref, titles and metadata only).
IISE_PARAGRAPH = r"""\paragraph{Selection and aggregation in industrial engineering}
\emph{IISE Transactions} has published work on aggregating pairwise comparisons to
find the top-ranked alternatives under an experimentation budget
\citep{mahpouya2026topk}, on optimization-based ensembles of classifiers
\citep{atsiz2026ensemble} and on adaptive sequential selection procedures
\citep{tsai2024quantile}. Those settings choose among alternatives measured with
noise. Here the alternatives are already-generated language-model answers, the
measurements are binary judge comparisons that each carry a price, and the
question is when a costly comparison should replace a free vote.

"""
ANCHOR = "Judgment aggregation and selection among forecasts provide a related OR"
assert ANCHOR in body
body = body.replace(ANCHOR, IISE_PARAGRAPH + ANCHOR, 1)
body = re.sub(r"\\ref\{S-", r"\\ref{S-", body)

tail = main[main.index("\\section*{Declaration of competing interest}"):main.index("\\bibliographystyle")]

anon_data = r"""\section*{Data availability statement}
The code, tables, pre-registration documents and stored run files that support the findings are archived in a
public repository. To preserve anonymity during double-blind review, the persistent identifier is given in the
submission form and an anonymized copy is provided with the submission; the identifier will be cited in the
accepted version. The archive excludes GPQA records containing password-gated question text, which cannot be
redistributed; access to that benchmark follows its distribution conditions. The analysis scripts regenerate all
tables from the stored runs and include the GPQA generation workflow.

"""

preamble = r"""% GENERATED by scripts/make_iise_manuscript.py -- do not edit by hand.
\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{setspace}
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage{amsthm}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage[section]{placeins}
\usepackage[authoryear,round]{natbib}
\usepackage{seqsplit}
\usepackage{url}
\usepackage{xr}
\externaldocument[S-]{supplement_iise}

\newtheorem{proposition}{Proposition}[section]
\newtheorem{theorem}{Theorem}[section]
\newtheorem{lemma}{Lemma}[section]
\newtheorem{corollary}{Corollary}[section]

""" + "\n".join(data_inputs) + r"""

\begin{document}
\setstretch{1.5}

\begin{center}
{\large\bfseries """ + title + r"""}
\end{center}

\begin{abstract}
""" + abstract + r"""
\end{abstract}

\noindent\textbf{Keywords:} """ + keywords + r"""

"""

closing = r"""
\bibliographystyle{chicago}
\bibliography{refs}

\end{document}
"""

(MS / "main_iise.tex").write_text(preamble + body + anon_data + tail + closing, encoding="utf-8")

s = supp.replace("\\externaldocument[M-]{main}", "\\externaldocument[M-]{main_iise}")
s = s.replace("\\author{Aris Dressino}", "\\author{}")
# The guide asks for 1.5 line spacing for the manuscript including references, tables, figures and appendices.
s = s.replace("\\usepackage{amsmath}", "\\usepackage{setspace}\n\\usepackage{amsmath}", 1)
s = s.replace("\\begin{document}", "\\begin{document}\n\\setstretch{1.5}", 1)
s = s.replace("\\bibliographystyle{apalike-local}", "\\bibliographystyle{chicago}")
(MS / "supplement_iise.tex").write_text("% GENERATED by scripts/make_iise_manuscript.py -- do not edit by hand.\n" + s, encoding="utf-8")
print("wrote main_iise.tex and supplement_iise.tex")
