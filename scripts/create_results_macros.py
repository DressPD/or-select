"""Compute every results number the manuscript quotes from outputs/*.json and write
manuscript/Results_data.tex (LaTeX \\def macros and ready-made table bodies).

    python3 scripts/create_results_macros.py

Nothing in the Results section is hand-typed: tables and prose macros come from here, so a
re-run after the benchmark passes finish refreshes the whole section. Coverage is always
reported as valid/total (total = benchmark size, not rows attempted).
"""

from __future__ import annotations

import json
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from or_select.reward_bench import wilson_interval  # noqa: E402

OUT = ROOT / "outputs"
DEST = ROOT / "manuscript" / "Results_data.tex"
METHODS = ("greedy", "self_consistency", "or_select", "kemeny_young")

# key, row label, output file, benchmark size, ground-truth track
TRACKS = [
    ("GSMh", r"B --- GSM8K, homog.", "gsm8k_benchmark_initial.json", 40),
    ("GSMx", r"B$'$ --- GSM8K, heterog.", "gsm8k_benchmark_heterogeneous.json", 40),
    ("MATHh", r"C --- MATH L5, homog.", "math_benchmark_full.json", 134),
    ("MATHx", r"C$'$ --- MATH L5, heterog.", "math_benchmark_heterogeneous.json", 134),
    ("AIMEh", r"D --- AIME 2026, homog.", "aime_2026_benchmark.json", 30),
    ("AIMEx", r"D$'$ --- AIME 2026, heterog.", "aime_2026_heterogeneous.json", 30),
    ("GPQAh", r"E --- GPQA Diamond, homog.", "gpqa_benchmark.json", 198),
    ("GPQAx", r"E$'$ --- GPQA Diamond, heterog.", "gpqa_heterogeneous.json", 198),
    # added tracks (homogeneous only); skipped until their output file exists
    ("AIME25h", r"F --- AIME 2025, homog.", "aime_2025_benchmark.json", 30),
    ("MMLUh", r"G --- MMLU-Pro, homog.", "mmlu_pro_benchmark.json", 100),
]


def mcnemar_exact_p(b: int, c: int) -> float | None:
    n = b + c
    if n == 0:
        return None
    k = min(b, c)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) * 0.5**n)


def fmt_p(p: float | None) -> str:
    if p is None:
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def prose_p(p: float | None) -> str:
    if p is None:
        return "$p$ undefined (no discordant pairs)"
    return "$p<0.001$" if p < 0.001 else f"$p={p:.3f}$"


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}" if n else "--"


def discordant(rows: list[dict], a: str, b: str) -> tuple[int, int]:
    return (
        sum(1 for r in rows if r[a]["correct"] and not r[b]["correct"]),
        sum(1 for r in rows if not r[a]["correct"] and r[b]["correct"]),
    )


def track_stats(path: Path, total: int) -> dict:
    data = json.loads(path.read_text())
    rows = data["results"]
    # A row graded by a superseded judge version is not comparable with the rest: leave it out.
    legacy = [r for r in rows if "error" not in r and r.get("judge_version") != "short-answer"]
    valid = [r for r in rows if "error" not in r and r.get("judge_version") == "short-answer"]
    failed = [r for r in rows if "error" in r]
    s = {
        "n_valid": len(valid),
        "total": total,
        "n_untried": total - len(rows),
        "n_legacy_judge": len(legacy),
        "n_trunc": sum(1 for r in failed if r.get("truncated")),
        "n_otherfail": sum(1 for r in failed if not r.get("truncated")),
        "n_rescued": sum(1 for r in valid if r.get("extended_cap_pass")),
        "has_ky": bool(valid) and "kemeny_young" in valid[0],
    }
    for m in METHODS:
        s[m] = sum(1 for r in valid if m in r and r[m]["correct"]) if valid and m in valid[0] else None
    s["b_sc"], s["c_sc"] = discordant(valid, "or_select", "self_consistency")
    s["p_sc"] = mcnemar_exact_p(s["b_sc"], s["c_sc"])
    s["b_gr"], s["c_gr"] = discordant(valid, "or_select", "greedy")
    s["p_gr"] = mcnemar_exact_p(s["b_gr"], s["c_gr"])
    if s["has_ky"]:
        s["b_ky"], s["c_ky"] = discordant(valid, "or_select", "kemeny_young")
        s["p_ky"] = mcnemar_exact_p(s["b_ky"], s["c_ky"])
        s["top1_differs_ky"] = sum(1 for r in valid if r["or_select"]["answer"] != r["kemeny_young"]["answer"])
    main = [r for r in valid if not r.get("extended_cap_pass")]
    s["n_main_valid"] = len(main)
    s["or_main"] = sum(1 for r in main if r["or_select"]["correct"])
    s["sc_main"] = sum(1 for r in main if r["self_consistency"]["correct"])
    s["legacy_laguna_rows"] = sum(
        1 for r in valid if any("laguna" in c.get("source_model", "") for c in (r.get("candidates") or []))
    )
    return s


def main() -> None:
    L = ["% Generated by scripts/create_results_macros.py from outputs/*.json -- do not hand-edit."]
    stats = {}
    for key, label, fname, total in TRACKS:
        if (OUT / fname).exists():
            stats[key] = track_stats(OUT / fname, total)
    TRACKS[:] = [t for t in TRACKS if t[0] in stats]

    # ---- main accuracy table (ground-truth tracks)
    rows_tex = []
    for key, label, _f, _t in TRACKS:
        s = stats[key]
        n = s["n_valid"]
        ky = pct(s["kemeny_young"], n) if s["kemeny_young"] is not None else "--"
        best = max(s[m] for m in ("self_consistency", "or_select", "greedy"))
        cells = []
        for m in ("greedy", "self_consistency", "or_select"):
            c = pct(s[m], n)
            cells.append(rf"\textbf{{{c}}}" if s[m] == best and len({s[x] for x in ('greedy','self_consistency','or_select')}) > 1 else c)
        rows_tex.append(f"{label} & {n}/{s['total']} & {cells[0]} & {cells[1]} & {cells[2]} & {ky} \\\\")
    L.append(r"\def\TracksTableRows{" + "\n".join(rows_tex) + "}")

    # ---- paired comparison table
    pair_rows = []
    for key, label, _f, _t in TRACKS:
        s = stats[key]
        ky = (
            f"{s['b_ky']}/{s['c_ky']} & {fmt_p(s['p_ky'])}"
            if s["has_ky"]
            else "-- & --"
        )
        pair_rows.append(
            f"{label} & {s['b_sc']}/{s['c_sc']} & {fmt_p(s['p_sc'])} & {s['b_gr']}/{s['c_gr']} & {fmt_p(s['p_gr'])} & {ky} \\\\"
        )
    L.append(r"\def\PairedTableRows{" + "\n".join(pair_rows) + "}")

    # ---- pooled homogeneous McNemar (OR-Select vs self-consistency) across the four homog tracks
    homog = [k for k in ("GSMh", "MATHh", "AIMEh", "GPQAh", "AIME25h", "MMLUh") if k in stats]
    pb = sum(stats[k]["b_sc"] for k in homog)
    pc = sum(stats[k]["c_sc"] for k in homog)
    pn = sum(stats[k]["n_valid"] for k in homog)
    L.append(r"\def\HomogPooledN{%d}" % pn)
    L.append(r"\def\HomogPooledB{%d}" % pb)
    L.append(r"\def\HomogPooledC{%d}" % pc)
    L.append(r"\def\HomogPooledP{%s}" % prose_p(mcnemar_exact_p(pb, pc)))
    L.append(r"\def\TotalProblems{%d}" % sum(stats[k]["total"] for k in homog))
    # figure coordinates (one group per track)
    figs = [("GSMh", "GSM8K"), ("GSMx", "GSM8K-H"), ("MATHh", "MATH5"), ("MATHx", "MATH5-H"),
            ("AIMEh", "AIME"), ("AIMEx", "AIME-H"), ("GPQAh", "GPQA"), ("GPQAx", "GPQA-H"),
            ("AIME25h", "AIME25"), ("MMLUh", "MMLU-Pro")]
    figs = [f for f in figs if f[0] in stats]
    L.append(r"\def\FigLabels{" + ",".join(lab for _k, lab in figs) + "}")
    for macro, m in (("GR", "greedy"), ("SC", "self_consistency"), ("OR", "or_select"), ("KY", "kemeny_young")):
        pts = [f"({lab},{100 * stats[k][m] / stats[k]['n_valid']:.1f})" for k, lab in figs if stats[k][m] is not None]
        L.append(r"\def\Fig" + macro + "Coordinates{" + " ".join(pts) + "}")
    hetero = [k for k in ("GSMx", "MATHx", "AIMEx", "GPQAx") if k in stats]
    hb = sum(stats[k]["b_sc"] for k in hetero)
    hc = sum(stats[k]["c_sc"] for k in hetero)
    hn = sum(stats[k]["n_valid"] for k in hetero)
    L.append(r"\def\HeteroPooledN{%d}" % hn)
    L.append(r"\def\HeteroPooledB{%d}" % hb)
    L.append(r"\def\HeteroPooledC{%d}" % hc)
    L.append(r"\def\HeteroPooledP{%s}" % prose_p(mcnemar_exact_p(hb, hc)))

    # ---- extended-cap protocol table (homog tracks that needed it, plus hetero in progress)
    ext_rows = []
    for key, label, _f, _t in TRACKS:
        s = stats[key]
        if s["n_rescued"] == 0:
            continue
        ext_rows.append(
            f"{label} & {s['n_main_valid']} & {pct(s['or_main'], s['n_main_valid'])} & {pct(s['sc_main'], s['n_main_valid'])}"
            f" & {s['n_rescued']} & {pct(s['or_select'], s['n_valid'])} & {pct(s['self_consistency'], s['n_valid'])} \\\\"
        )
    L.append(r"\def\ExtendedTableRows{" + "\n".join(ext_rows) + "}")

    # ---- coverage table
    cov_rows = []
    for key, label, _f, _t in TRACKS:
        s = stats[key]
        cov_rows.append(
            f"{label} & {s['total']} & {s['n_valid']} & {s['n_trunc']} & {s['n_otherfail'] + s['n_legacy_judge']} & {s['n_untried']}"
            f" & {s['legacy_laguna_rows'] if label.find('heterog') >= 0 else '--'} \\\\"
        )
    L.append(r"\def\CoverageTableRows{" + "\n".join(cov_rows) + "}")

    # ---- Kemeny top-1 agreement over tracks that have it
    ky_n = sum(s["n_valid"] for s in stats.values() if s["has_ky"])
    ky_diff = sum(s["top1_differs_ky"] for s in stats.values() if s["has_ky"])
    L.append(r"\def\KYTopOneN{%d}" % ky_n)
    L.append(r"\def\KYTopOneDiffers{%d}" % ky_diff)
    kyb = sum(stats[k]["b_ky"] for k in stats if stats[k]["has_ky"])
    kyc = sum(stats[k]["c_ky"] for k in stats if stats[k]["has_ky"])
    L.append(r"\def\KYORwins{%d}" % kyb)
    L.append(r"\def\KYKYwins{%d}" % kyc)

    # ---- per-track scalar macros for prose
    for key, s in stats.items():
        n = s["n_valid"]
        L.append(rf"\def\N{key}{{{n}}}")
        L.append(rf"\def\Tot{key}{{{s['total']}}}")
        for m, tag in (("or_select", "OR"), ("self_consistency", "SC"), ("greedy", "GR"), ("kemeny_young", "KY")):
            if s[m] is not None:
                L.append(rf"\def\Acc{tag}{key}{{{pct(s[m], n)}}}")
        L.append(rf"\def\Disc{key}{{{s['b_sc'] + s['c_sc']}}}")
        L.append(rf"\def\ORwins{key}{{{s['b_sc']}}}")
        L.append(rf"\def\SCwins{key}{{{s['c_sc']}}}")
        L.append(rf"\def\Legacy{key}{{{s['legacy_laguna_rows']}}}")

    # ---- RewardBench: homogeneous judge and rotating-judge variants
    for tag, fname in (("", "reward_bench_benchmark.json"), ("X", "reward_bench_benchmark_heterogeneous.json")):
        rb = json.loads((OUT / fname).read_text())
        cats = rb["category_scores"]
        lo, hi = rb["overall_ci95_micro"]
        L.append(rf"\def\RB{tag}OverallAcc{{{rb['overall_accuracy'] * 100:.1f}}}")
        L.append(rf"\def\RB{tag}N{{{rb['n_valid']}}}")
        L.append(rf"\def\RB{tag}CILow{{{lo * 100:.1f}}}")
        L.append(rf"\def\RB{tag}CIHigh{{{hi * 100:.1f}}}")
        for cat, name in (("Chat", "Chat"), ("Reasoning", "Reasoning"), ("Chat Hard", "ChatHard"), ("Safety", "Safety")):
            L.append(rf"\def\RB{tag}{name}Acc{{{cats[cat]['accuracy'] * 100:.1f}}}")
            L.append(rf"\def\RB{tag}{name}Rows{{{cats[cat]['n_rows']}}}")
            L.append(rf"\def\RB{tag}{name}Correct{{{round(cats[cat]['accuracy'] * cats[cat]['n_rows'])}}}")
        micro = sum(round(c["accuracy"] * c["n_rows"]) for c in cats.values())
        L.append(rf"\def\RB{tag}MicroAcc{{{100 * micro / rb['n_valid']:.1f}}}")

    # ---- RewardBench length-bias split (homogeneous judge)
    sample = {}
    for line in (ROOT / "data" / "reward_bench_sample.jsonl").read_text().splitlines():
        if line.strip():
            row = json.loads(line)
            sample[row["id"]] = row
    rbres = [r for r in json.loads((OUT / "reward_bench_benchmark.json").read_text())["results"] if "error" not in r]
    b = {"chosen_longer": [0, 0], "rejected_longer": [0, 0]}
    for r in rbres:
        row = sample[r["id"]]
        key = "chosen_longer" if len(row["chosen"]) > len(row["rejected"]) else "rejected_longer"
        b[key][1] += 1
        b[key][0] += bool(r["correct"])
    for key, tag in (("chosen_longer", "ChosenLonger"), ("rejected_longer", "RejectedLonger")):
        k, n = b[key]
        lo, hi = wilson_interval(k, n)
        L.append(rf"\def\RB{tag}K{{{k}}}")
        L.append(rf"\def\RB{tag}N{{{n}}}")
        L.append(rf"\def\RB{tag}Acc{{{100 * k / n:.1f}}}")
        L.append(rf"\def\RB{tag}CILow{{{100 * lo:.1f}}}")
        L.append(rf"\def\RB{tag}CIHigh{{{100 * hi:.1f}}}")

    DEST.write_text("\n".join(L) + "\n")
    print("wrote", DEST)
    for key, label, _f, _t in TRACKS:
        s = stats[key]
        print(
            f"{key:6} {s['n_valid']:>3}/{s['total']:<3} OR {s['or_select']} SC {s['self_consistency']} GR {s['greedy']}"
            f" KY {s['kemeny_young']} | OR-vs-SC {s['b_sc']}/{s['c_sc']} p={fmt_p(s['p_sc'])}"
            f" | trunc {s['n_trunc']} fail {s['n_otherfail']} untried {s['n_untried']} rescued {s['n_rescued']}"
            f" legacy-laguna {s['legacy_laguna_rows']}"
        )
    print("homog pooled OR>SC / SC>OR:", pb, pc, "p", fmt_p(mcnemar_exact_p(pb, pc)), "n", pn)
    print("hetero pooled OR>SC / SC>OR:", hb, hc, "p", fmt_p(mcnemar_exact_p(hb, hc)), "n", hn)
    print("KY top-1 differs", ky_diff, "of", ky_n, "| OR-only-correct", kyb, "KY-only-correct", kyc)
    print("RB length split:", b)


if __name__ == "__main__":
    main()
