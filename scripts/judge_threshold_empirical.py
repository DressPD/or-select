"""Empirical thresholds with correlated wrong answers: q*(p-hat, N, rho-hat) against the measured pairwise judge accuracy q-hat.

    python3 scripts/judge_threshold_empirical.py

Zero API calls. For each track with enough mixed pairs: p-hat (share of correct candidates), rho-hat (square root of the
agreement rate between two wrong candidates of the same problem, answers extracted, ungraded ones skipped; under the
attractor model two wrong candidates agree with probability rho^2), q-hat (mean stored pairwise probability given to the
correct candidate over ordered mixed pairs) and the exact threshold q*(p-hat, N, rho-hat) from judge_threshold_general.
N is 3 for the homogeneous tracks and 6 for the heterogeneous ones. Writes manuscript/ThresholdEmpiricalGeneral_data.tex.
"""

from __future__ import annotations

import itertools
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
import judge_threshold_general as gen  # noqa: E402
import judge_threshold_theory as th  # noqa: E402

DEST = ROOT / "manuscript" / "ThresholdEmpiricalGeneral_data.tex"


def stats(fname: str, kind: str):
    path = th.OUT / fname
    if not path.exists():
        return None
    ncand = nok = 0
    agree = pairs = 0
    per_problem = []  # (agreeing wrong pairs, wrong pairs) per problem, for the bootstrap
    mixed = []
    for row in json.loads(path.read_text())["results"]:
        if "error" in row or row.get("judge_version") != "short-answer":
            continue
        ans = [th.EXTRACT[kind](c["text"]) for c in row["candidates"]]
        ok = [bool(th.CORRECT[kind](a, row["ground_truth"])) for a in ans]
        ncand += len(ok)
        nok += sum(ok)
        wrong = [a for a, o in zip(ans, ok) if not o and a is not None]
        a_i = n_i = 0
        for x, y in itertools.combinations(wrong, 2):
            n_i += 1
            a_i += str(x) == str(y)
        pairs += n_i
        agree += a_i
        per_problem.append((a_i, n_i))
        j = row.get("judgments")
        if j:
            for a, b in itertools.permutations(range(len(ok)), 2):
                if ok[a] and not ok[b]:
                    mixed.append(j["pairwise"][f"c{a}|c{b}"])
    return ncand, nok, agree, pairs, mixed, per_problem


def main() -> None:
    rows = []
    for het, tracks, N in ((False, th.HOMOG, 3), (True, th.HETERO, 6)):
        for label, fname, kind in tracks:
            s = stats(fname, kind)
            if not s or len(s[4]) < 20 or s[3] == 0:
                continue
            ncand, nok, agree, pairs, mixed, per_problem = s
            p, q = nok / ncand, sum(mixed) / len(mixed)
            rho = (agree / pairs) ** 0.5
            rng = random.Random(0)
            boots = []
            for _ in range(400):  # bootstrap over problems
                draw = [per_problem[rng.randrange(len(per_problem))] for _ in per_problem]
                a, n = sum(d[0] for d in draw), sum(d[1] for d in draw)
                if n:
                    boots.append((a / n) ** 0.5)
            boots.sort()
            lo, hi = boots[int(0.025 * len(boots))], boots[int(0.975 * len(boots)) - 1]
            q0 = gen.q_star_exact(N, p, 0.0)
            q_hi, q_lo = gen.q_star_exact(N, p, hi), gen.q_star_exact(N, p, lo)  # larger rho -> lower threshold
            q1 = gen.q_star_exact(N, p, rho)
            if pairs < 30:  # too few wrong pairs to estimate rho: report the bounds over every possible rho instead
                q_all = gen.q_star_exact(N, p, 1.0)
                rows.append(
                    f"{label}{'' if not het else '-H'} & {N} & {p:.3f} & {pairs} & n/a & {q:.3f} & {q0:.3f} & [{q_all:.3f}, {q0:.3f}]$^{{\\ddagger}}$ \\\\"
                )
                print(rows[-1])
                continue
            rows.append(
                f"{label}{'' if not het else '-H'} & {N} & {p:.3f} & {pairs} & {rho:.2f} [{lo:.2f}, {hi:.2f}] & {q:.3f} & {q0:.3f} & {q1:.3f} [{q_hi:.3f}, {q_lo:.3f}] \\\\"
            )
            print(rows[-1])
    DEST.write_text(
        "% Generated by scripts/judge_threshold_empirical.py -- do not hand-edit.\n"
        + r"\def\ThresholdEmpGenRows{" + "\n".join(rows) + "}\n"
    )
    print("wrote", DEST)


if __name__ == "__main__":
    main()
